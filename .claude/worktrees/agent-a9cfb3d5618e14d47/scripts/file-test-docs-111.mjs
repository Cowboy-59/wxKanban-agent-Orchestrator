#!/usr/bin/env node
/**
 * File the SPEC-111 test-plan documents through the hosted MCP
 * (project.upsert_document). Script-invoked because the bodies are large.
 *
 *   node scripts/file-test-docs-111.mjs [--dry-run]
 *
 * The TEST-PLAN body is truncated at section 12 ON PURPOSE. Section 12 is the
 * full record of all 160 items, and those items are now first-class rows in
 * `testplanitems` — queryable, re-runnable and rendered to a tester as steps.
 * Copying them into a document body would recreate the exact defect SCOPE-111
 * exists to fix: a suite that stops being a suite and becomes prose. The document
 * carries the PLAN (scope, tiers, criteria, risk register, data strategy, the DBA
 * sections, clarifications, and the item index); the items carry themselves.
 */
import { readFileSync } from 'node:fs';

const DIR = 'tests/testplans/111-test-suite-lifecycle';
const dryRun = process.argv.includes('--dry-run');
const MCP_URL = process.env.WXKANBAN_MCP_URL || 'https://mcp.wxperts.com/mcp';
const TOKEN = process.env.WXKANBAN_API_TOKEN;
if (!TOKEN) { console.error('WXKANBAN_API_TOKEN not set'); process.exit(1); }

const PROJECT_ID = 'ba924193-0335-4080-9fa6-33cd6b81300a';
const SPEC_ID = 'f5552f9a-e581-46d1-8cdf-6e09569d1b22';

let callId = 1;
async function callTool(name, args) {
  const res = await fetch(MCP_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream', Authorization: `Bearer ${TOKEN}` },
    body: JSON.stringify({ jsonrpc: '2.0', id: callId++, method: 'tools/call', params: { name, arguments: args } }),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${text.slice(0, 400)}`);
  const line = text.startsWith('event:') || text.startsWith('data:')
    ? text.split('\n').filter((l) => l.startsWith('data:')).map((l) => l.slice(5).trim()).join('')
    : text;
  const parsed = JSON.parse(line);
  if (parsed.error) throw new Error(`tool error: ${JSON.stringify(parsed.error).slice(0, 400)}`);
  const content = parsed.result?.content?.[0]?.text;
  try { return content ? JSON.parse(content) : parsed.result; } catch { return content; }
}

const plan = readFileSync(`${DIR}/TEST-PLAN.md`, 'utf8');
const cut = plan.indexOf('\n## 12. Full item records');
const planBody =
  (cut > 0 ? plan.slice(0, cut) : plan) +
  `\n## 12. Full item records\n\n` +
  `The 160 item records are **not duplicated here.** They are first-class rows in \`testplanitems\`\n` +
  `under plan \`b45c6863-0784-4add-b549-1d31b77eb7e1\`, each carrying its preconditions, ordered steps\n` +
  `with a machine-checkable expected value per step, test data, flow, postconditions and declared\n` +
  `subjects. Read them through \`GET /api/testplans/:id/items\`, the QA and User Testing views, or\n` +
  `\`tests/testplans/111-test-suite-lifecycle/test-items.json\`.\n\n` +
  `Copying them into this document is what the scope exists to prevent: the moment a suite is written\n` +
  `into prose it stops being executable, re-runnable or gateable. Section 11 above is the index.\n`;

const schema = readFileSync(`${DIR}/schema-analysis.json`, 'utf8');
const s = JSON.parse(schema);
const ri = s.referentialIntegrity;
const schemaBody = [
  '# Database schema analysis — wxKanban',
  '',
  `Generated by \`wxCreateTestPlan/scripts/schema-analyze.mjs\`. Scanned ${s.scanned.tables} tables across ${s.scanned.files} files.`,
  '',
  `## Referential integrity: ${ri.score} / 10 — ${ri.band}`,
  '',
  `FK candidates ${ri.fkCandidates} · unenforced ${ri.components.unenforcedFk} · missing onDelete ${ri.components.fkNoOnDelete} · FK without a covering index ${ri.components.fkNoIndex}`,
  '',
  '> **This score supersedes an earlier run that reported 5.0/10.** That figure was wrong: the analyzer',
  '> carried seven parsing defects, the worst of which captured the `onDelete` value with `\\w+` and so',
  '> could not match `"set null"` — every set-null foreign key in the repository read as having no rule,',
  '> producing 47 false findings while `cascade` matched fine. Five further defects and a whole-table',
  '> blind spot were fixed in the same pass, and the behaviour is now pinned by',
  '> `tests/unit/schema-analyze-parser.test.ts`. Do not compare this score against the earlier one.',
  '',
  '## Findings by dimension',
  '',
  '| Dimension | Count |',
  '|---|---|',
  ...Object.entries(s.totals.byDimension).map(([k, v]) => `| ${k} | ${v} |`),
  '',
  '## Referential integrity findings',
  '',
  '| Table | Line | Issue | File |',
  '|---|---|---|---|',
  ...s.findings.referentialIntegrity.map((f) => `| ${f.table} | ${f.line} | ${String(f.issue).replace(/\|/g, '\\|')} | ${f.file} |`),
  '',
  '## Missing indexes',
  '',
  '| Table | Line | Issue | Remediation |',
  '|---|---|---|---|',
  ...s.findings.missingIndexes.slice(0, 200).map((f) => `| ${f.table} | ${f.line} | ${String(f.issue).replace(/\|/g, '\\|')} | ${String(f.fix ?? '').replace(/\|/g, '\\|')} |`),
  '',
  '## Excessive / redundant indexes',
  '',
  '| Table | Line | Issue | Remediation |',
  '|---|---|---|---|',
  ...s.findings.excessiveIndexes.map((f) => `| ${f.table} | ${f.line} | ${String(f.issue).replace(/\|/g, '\\|')} | ${String(f.fix ?? '').replace(/\|/g, '\\|')} |`),
  '',
].join('\n');

const inv = JSON.parse(readFileSync(`${DIR}/inventory.json`, 'utf8'));
const invClient = JSON.parse(readFileSync(`${DIR}/inventory-client.json`, 'utf8'));
const S111 = ['routes/testplans.ts', 'services/TestCycleService', 'services/TestGateService', 'services/TestImpactService', 'services/TestPlanService', 'services/TestRegressionService', 'services/TestRunService', 'services/TestSignoffService', 'services/TestFailureReportService', 'services/PhaseService'];
const s111 = inv.units.filter((u) => S111.some((p) => u.file.includes(p)));
const routes = s111.filter((u) => u.kind === 'express-route');
const invBody = [
  '# Callable-unit inventory — SCOPE-111 surface',
  '',
  `Whole-app scan: **${inv.units.length}** server units across ${inv.scanned.files} files, plus **${invClient.units.length}** client units.`,
  '',
  '## SCOPE-111 surface (the requirement-driven target)',
  '',
  '| Area | Units |',
  '|---|---|',
  `| Express routes | ${routes.length} |`,
  `| Service methods and functions | ${s111.length - routes.length} |`,
  '| Drizzle tables | 8 (+ `companyprojects.skiptesting`) |',
  '| MCP tools | 7 |',
  '| Client components | 8 |',
  '',
  `**Completeness cross-check:** the extractor found ${routes.length} \`router.<verb>\` call sites in`,
  '`src/server/routes/testplans.ts`, and a raw grep of the same file finds the same number. No discrepancy.',
  '',
  '## The routes',
  '',
  '| Method + path | Line | Risk |',
  '|---|---|---|',
  ...routes.map((r) => `| \`${r.name}\` | ${r.line} | ${r.risk} |`),
  '',
  '> Regenerate and diff before re-planning; do not hand-edit. New units are untested, deleted units',
  '> mean stale tests, and a changed signature means a suspect test.',
  '',
].join('\n');

const docs = [
  { title: 'SPEC-111 Test Suite Lifecycle — Test Plan', doctype: 'TestPlan', body: planBody, tags: ['testing', 'scope-111', 'istqb'] },
  { title: 'Database Schema Analysis', doctype: 'SchemaAnalysis', body: schemaBody, tags: ['testing', 'schema', 'referential-integrity'] },
  { title: 'SPEC-111 Callable-Unit Inventory', doctype: 'TestInventory', body: invBody, tags: ['testing', 'scope-111', 'inventory'] },
];

for (const d of docs) {
  const kb = (d.body.length / 1024).toFixed(0);
  process.stdout.write(`  ${d.doctype.padEnd(15)} "${d.title}" (${kb} KB) ... `);
  if (dryRun) { console.log('dry-run'); continue; }
  try {
    const r = await callTool('project.upsert_document', {
      projectId: PROJECT_ID,
      specId: SPEC_ID,
      doctype: d.doctype,
      title: d.title,
      bodyMarkdown: d.body,
      tags: d.tags,
    });
    console.log(`ok  ${JSON.stringify(r).slice(0, 160)}`);
  } catch (err) {
    console.log('FAILED');
    console.error(`    ${err.message}`);
    process.exitCode = 1;
  }
}
