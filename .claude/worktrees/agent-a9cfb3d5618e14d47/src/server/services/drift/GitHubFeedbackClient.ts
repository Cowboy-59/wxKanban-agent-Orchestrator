import { createLogger } from "~/server/lib/logger.js";
import type { DriftEventInput } from "~/shared/types/gateway.js";

const logger = createLogger("github-feedback-client");

interface GitHubIssuePayload {
  title: string;
  body: string;
  labels?: string[];
}

interface GitHubIssueResponse {
  html_url?: string;
  number?: number;
}

export class GitHubFeedbackClient {
  private readonly token = process.env.GITHUB_TOKEN;
  private readonly owner = process.env.MCP_FEEDBACK_REPO_OWNER || "Cowboy-59";
  private readonly repo = process.env.MCP_FEEDBACK_REPO_NAME || "wxKanban";

  async createDriftIssue(input: DriftEventInput): Promise<string> {
    const payload: GitHubIssuePayload = {
      title: `[MCP Drift] ${input.projectidentifier} ${input.severity.toUpperCase()} drift`,
      body: [
        "Automated drift report generated by Spec 018 parity checks.",
        "",
        `Project: ${input.projectidentifier}`,
        `Main MCP Version: ${input.mcpversionmain}`,
        `Kit MCP Version: ${input.mcpversionkit}`,
        `Severity: ${input.severity}`,
        "",
        "Changed Paths:",
        ...input.changedpaths.map((path) => `- ${path}`),
      ].join("\n"),
      labels: ["mcp-drift", `severity:${input.severity}`],
    };

    const issue = await this.createIssue(payload);
    return issue ?? this.buildLocalReference(input.projectidentifier);
  }

  async resolveDriftIssue(reference: string, note?: string): Promise<void> {
    if (!this.token || !reference.startsWith("https://github.com/")) {
      logger.info({ reference, note }, "Skipping GitHub drift resolution update");
      return;
    }

    const match = reference.match(/github\.com\/([^/]+)\/([^/]+)\/issues\/(\d+)/i);
    if (!match) {
      logger.warn({ reference }, "Unable to parse GitHub issue reference");
      return;
    }

    const [, owner, repo, issueNumber] = match;
    await fetch(`https://api.github.com/repos/${owner}/${repo}/issues/${issueNumber}`, {
      method: "PATCH",
      headers: this.headers(),
      body: JSON.stringify({ state: "closed", state_reason: "completed" }),
    });

    if (note) {
      await fetch(`https://api.github.com/repos/${owner}/${repo}/issues/${issueNumber}/comments`, {
        method: "POST",
        headers: this.headers(),
        body: JSON.stringify({ body: `Resolved in wxKanban. ${note}` }),
      });
    }
  }

  private async createIssue(payload: GitHubIssuePayload): Promise<string | null> {
    if (!this.token) {
      logger.info({ owner: this.owner, repo: this.repo }, "GITHUB_TOKEN not configured; using local drift reference");
      return null;
    }

    try {
      const response = await fetch(`https://api.github.com/repos/${this.owner}/${this.repo}/issues`, {
        method: "POST",
        headers: this.headers(),
        body: JSON.stringify(payload),
      });

      if (!response.ok) {
        logger.warn({ status: response.status }, "GitHub issue creation failed");
        return null;
      }

      const issue = (await response.json()) as GitHubIssueResponse;
      return issue.html_url ?? null;
    } catch (error) {
      logger.warn({ error }, "GitHub issue creation threw");
      return null;
    }
  }

  private headers(): HeadersInit {
    return {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${this.token}`,
      "Content-Type": "application/json",
      "User-Agent": "wxkanban-mcp-feedback-client",
    };
  }

  private buildLocalReference(projectIdentifier: string): string {
    return `local://mcp-drift/${projectIdentifier}/${Date.now()}`;
  }
}
