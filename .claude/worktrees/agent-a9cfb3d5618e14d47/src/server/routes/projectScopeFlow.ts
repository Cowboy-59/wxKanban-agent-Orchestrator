import { Router, Response } from 'express';
import { eq, and } from 'drizzle-orm';
import { db } from '~/db/client.js';
import { companyprojects } from '~/db/schema/companyproject.js';
import { authenticateToken, requireAuth, type AuthRequest } from '~/server/middleware/auth.js';
import { asyncHandler } from '~/server/middleware/errorHandler.js';
import { createLogger } from '~/server/lib/logger.js';
import { ProjectDocumentService } from '~/server/services/ProjectDocumentService.js';

const router = Router();
const logger = createLogger('project-scopeflow-route');

async function projectInCompany(projectid: string, companyid: string | undefined): Promise<boolean> {
  if (!companyid) return false;
  const [row] = await db
    .select({ id: companyprojects.id })
    .from(companyprojects)
    .where(and(eq(companyprojects.id, projectid), eq(companyprojects.companyid, companyid)))
    .limit(1);
  return !!row;
}

/**
 * GET /api/projects/:id/scopeflow
 * Returns the stored scope-flow markdown (a ```mermaid``` graph + graph-health warnings) for
 * inline rendering. The doc is generated by the MCP (doctype='scopeflow') and read here from the
 * shared DB. 404 when none exists yet (e.g. no dependencies captured).
 */
router.get(
  '/api/projects/:id/scopeflow',
  authenticateToken,
  requireAuth,
  asyncHandler(async (req: AuthRequest, res: Response) => {
    const projectid = String(req.params.id);
    if (!(await projectInCompany(projectid, req.companyid))) {
      res.status(404).json({ error: 'Project not found' });
      return;
    }

    const doc = await ProjectDocumentService.getScopeFlow(projectid);
    if (!doc) {
      res.status(404).json({
        error: 'No scope-flow generated for this project yet',
        hint: 'Generated automatically on create_specs / implement / set_scope_dependencies',
      });
      return;
    }

    res.setHeader('Cache-Control', 'private, max-age=30');
    res.json({ markdown: doc.content, updatedat: doc.updatedat });
    logger.info({ projectid, bytes: doc.content.length }, 'Scope-flow served');
  })
);

// Note: there is intentionally no server-rendered /scopeflow/pdf route. App Runner's managed
// Node runtime can't launch Chromium (missing libnspr4.so), so on-the-fly PDF render 500s there;
// and the scope-flow doc is auto-rewritten on every scope/spec/task change, so a stored PDF would
// go stale. The Portfolio Analyzer tab renders the graph live (Mermaid) and offers a client-side
// "Download PDF" (browser print) instead — see PortfolioAnalyzerTab.tsx.

export default router;
