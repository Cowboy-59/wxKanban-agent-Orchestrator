// SCOPE-114 (SPEC-116 / T010) — the `DESIGN.md` renderer.
//
// This file is written for TWO readers, which is why it carries prose and a table rather than
// one or the other:
//
//   The AI implementation agent, which consumes it as build context. It needs the resolved
//   values — the actual radius steps, the actual type metrics — because "use a tight radius"
//   is not something it can act on, and it needs to know which parts were approximated so it
//   does not reproduce an approximation as though it were captured intent.
//
//   The customer, who needs to know what typeface to license, which controls they were given,
//   and which ones the system declared but the bundle deliberately did not generate.
//
// Two hard rules govern the output. The originating brand appears NOWHERE: the analysis prose
// and font stack are redacted at ingest (`src/ingest/designsystems/redact.ts`) rather than
// here, so this renderer emits already-clean text, and `sourcebrand` is never passed in. And
// no font binary ships — the intended typeface is NAMED so the customer can license it
// themselves, which is the only defensible position when roughly 45 of the 50 captured
// systems use a proprietary or trademarked face.

import type { DesignSystemTokens } from "./design-system.js";
import type { ProjectTheme } from "./theme-tokens.js";
import { CONTROL_VARIANT_THRESHOLD } from "./design-system.js";
import { ADMITTED_BUTTON_EXTRAS, type ControlRenderResult } from "./design-system-controls.js";
import { dsVar, typeVars } from "./design-system-css.js";

/** Everything DESIGN.md needs. All brand-bearing fields are pre-redacted by ingest. */
export interface DesignDocInput {
  /** The curated, descriptive name — never the source brand. */
  name: string;
  /** The redacted prose analysis, or null for a hand-built theme. */
  analysis: string | null;
  /** The loadable font stack resolved at ingest. */
  fontStack: string | null;
  /** The typeface the system intended, for licensing. */
  intendedFont: string | null;
  /** Which mode was approximated rather than captured. */
  synthesizedMode: "light" | "dark" | "none" | null;
  /** The resolved project theme — the current colour source of truth. */
  theme: ProjectTheme;
  /** The captured geometry, or null for a colour-only theme. */
  tokens: DesignSystemTokens | null;
  /** What the control render produced, or null when no controls were emitted. */
  controls: ControlRenderResult | null;
}

/** Escape a value for a markdown table cell so a stray pipe cannot break the row. */
// [SCOPE 116 / T010] BEGIN — DESIGN.md renderer + execute wiring with colour-only fallback
function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}
// [SCOPE 116 / T010] END

/** Render a two-column scale table, or nothing when the scale is empty. */
// [SCOPE 116 / T010] BEGIN — DESIGN.md renderer + execute wiring with colour-only fallback
function scaleTable(
  heading: string,
  group: string,
  scale: Record<string, string>,
  valueHeader: string,
): string[] {
  const entries = Object.entries(scale);
  if (entries.length === 0) return [];
  return [
    `### ${heading}`,
    "",
    `| Step | ${valueHeader} | CSS variable |`,
    "|------|" + "-".repeat(valueHeader.length + 2) + "|--------------|",
    ...entries.map(([key, value]) => `| \`${cell(key)}\` | \`${cell(value)}\` | \`var(${dsVar(group, key)})\` |`),
    "",
  ];
}
// [SCOPE 116 / T010] END

/**
 * Render `DESIGN.md` for a resolved theme.
 *
 * Degrades cleanly rather than branching into two renderers: a theme with no `tokens` still
 * produces a valid document carrying the colour tokens, the radius and the font, because
 * FR-010 requires the colour-only path to keep working and a bundle whose documentation
 * disappears when the rich set is absent is a worse artifact than a shorter one.
 */
// [SCOPE 116 / T010] BEGIN — DESIGN.md renderer + execute wiring with colour-only fallback
export function renderDesignMd(input: DesignDocInput): string {
  const { name, analysis, fontStack, intendedFont, synthesizedMode, theme, tokens, controls } = input;
  const lines: string[] = [];

  lines.push(
    `# ${name} — Design System`,
    "",
    "Generated by wxKanban. This document is build context: it describes the visual system",
    "your generated application should follow, with every value resolved to what the code",
    "actually emits.",
    "",
  );

  if (analysis && analysis.trim() !== "") {
    lines.push("## Design language", "", analysis.trim(), "");
  }

  // ── Typography ────────────────────────────────────────────────────────────
  lines.push("## Typography", "");
  if (intendedFont) {
    lines.push(
      `**Intended typeface:** ${intendedFont}`,
      "",
      "No font binary ships with this bundle. If the intended typeface is proprietary you must",
      "license it yourself; until you do, the stack below falls back to a freely available",
      "substitute that preserves the system's proportions.",
      "",
    );
  }
  if (fontStack) lines.push(`**Loadable stack:** \`${cell(fontStack)}\``, "");
  lines.push(`**Applied family:** \`${cell(theme.typography.fontFamily)}\``, "");
  lines.push(`**Scale summary:** ${cell(theme.typography.scale)}`, "");

  if (tokens && Object.keys(tokens.typography).length > 0) {
    lines.push(
      "### Type roles",
      "",
      "| Role | Size | Weight | Line height | Tracking | CSS variables |",
      "|------|------|--------|-------------|----------|---------------|",
    );
    for (const [role, metrics] of Object.entries(tokens.typography)) {
      const v = typeVars(role);
      lines.push(
        `| \`${cell(role)}\` | ${cell(String(metrics.fontSize))} | ${cell(String(metrics.fontWeight))} | ` +
          `${cell(String(metrics.lineHeight))} | ${cell(String(metrics.letterSpacing))} | \`${v.size}\` … |`,
      );
    }
    lines.push("");
  }

  // ── Colour ────────────────────────────────────────────────────────────────
  lines.push(
    "## Colour",
    "",
    "Colour is authoritative in `theme.css` and is the ONLY layer you should edit. Every",
    "generated control references it through shadcn semantic classes (`bg-primary`,",
    "`text-muted-foreground`, `border-border`), so recolouring your theme updates every",
    "control with no regeneration — and no control can drift out of step with it.",
    "",
    "| Token | Light | Dark |",
    "|-------|-------|------|",
  );
  for (const key of Object.keys(theme.light) as Array<keyof typeof theme.light>) {
    lines.push(`| \`--${String(key)}\` | \`${cell(theme.light[key])}\` | \`${cell(theme.dark[key])}\` |`);
  }
  lines.push("");
  if (synthesizedMode && synthesizedMode !== "none") {
    lines.push(
      `> **The ${synthesizedMode} mode was approximated, not captured.** The source system is`,
      `> single-mode, so its ${synthesizedMode} counterpart was synthesized and checked for WCAG AA`,
      "> contrast. It is a sound starting point rather than the designer's intent — tune it in the",
      "> Theme Studio if this mode matters to your product.",
      "",
    );
  }

  // ── Geometry ──────────────────────────────────────────────────────────────
  lines.push("## Geometry", "");
  lines.push(`**Base radius:** \`${cell(theme.radius)}\` (\`var(--radius)\`)`, "");
  if (tokens) {
    lines.push(...scaleTable("Radius steps", "radius", tokens.rounded, "Value"));
    lines.push(...scaleTable("Spacing steps", "space", tokens.spacing, "Value"));
    lines.push(...scaleTable("Elevation levels", "elevation", tokens.elevation, "Box shadow"));
  } else {
    lines.push(
      "This theme carries no captured geometry scale, so the bundle emits colour, radius and",
      "font only. Pick a design system from the catalog to get spacing, elevation, a full type",
      "scale and generated controls.",
      "",
    );
  }

  // ── Controls ──────────────────────────────────────────────────────────────
  if (controls) {
    lines.push(
      "## Controls",
      "",
      "The following components were generated into `components/ui/`. They carry the captured",
      "geometry as Tailwind arbitrary values and take all colour from the semantic classes",
      "above — there is not a single colour literal in any of them, by construction.",
      "",
      "| File | Component |",
      "|------|-----------|",
      ...controls.files.map((f) => `| \`${cell(f.path)}\` | \`${cell(f.path.split("/").pop() ?? "")}\` |`),
      "",
      `**Button variants:** ${controls.buttonVariants.map((v) => `\`${v}\``).join(", ")}`,
      "",
    );

    if (controls.documentedOnly.length > 0) {
      lines.push(
        "### Declared but not generated",
        "",
        `A control the source system declares becomes a generated variant only when at least`,
        `${CONTROL_VARIANT_THRESHOLD} of the 50 catalogued systems declare it too — the admitted set being`,
        `${ADMITTED_BUTTON_EXTRAS.map((e) => `\`${e.control}\` (${e.seen}/50)`).join(", ")}.`,
        "Below that line a control is one system's one-off, and generating it would ship code",
        "shaped by a single example. These were captured and are described here so you can build",
        "them deliberately; their full specification is preserved in the stored tokens.",
        "",
        ...controls.documentedOnly.map((c) => {
          const spec = tokens?.components[c];
          const detail = spec
            ? Object.entries(spec)
                .map(([k, v]) => `${k}: ${v}`)
                .join("; ")
            : "";
          return `- \`${cell(c)}\`${detail ? ` — ${cell(detail)}` : ""}`;
        }),
        "",
      );
    }

    if (controls.notes.length > 0) {
      lines.push(
        "### Approximations made while generating",
        "",
        "Each entry below is a place where the source specification could not be reproduced",
        "exactly and a theme-driven equivalent was substituted. They are listed rather than",
        "silently applied so you can decide whether any of them matters to your product.",
        "",
        ...controls.notes.map((n) => `- ${cell(n)}`),
        "",
      );
    }
  }

  lines.push(
    "## How to use this bundle",
    "",
    "1. Paste the generated `:root` / `.dark` blocks from `theme.css` into your global stylesheet.",
    "2. Spread `themeExtend` from `tailwind.theme.ts` into your Tailwind config's `theme.extend`.",
    "3. Drop the `components/ui/*.tsx` files into your project.",
    "4. Edit colour in `theme.css` only. Geometry lives in the `--ds-*` custom properties.",
    "",
  );

  return lines.join("\n");
}
// [SCOPE 116 / T010] END
