// Generates src/prompts/registry.ts from the readable server-side prompt bodies
// in src/prompts/*.md. Each prompt is embedded base64 (no escaping fragility) so
// it compiles into dist/ — no runtime fs/path resolution, works under ESM.
//
// Premium command/skill methodology bodies live ONLY here (server-side); they are
// never shipped to consumers. The kit fetches them at runtime via
// project.get_command_prompt, gated by entitlement.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, '..', 'src', 'prompts');

// Walk recursively: a command's on-demand reference documents live in a sibling
// folder (e.g. src/prompts/wxgod.md + src/prompts/wxgod/references/*.md) and are
// keyed by their path, forward slashes, without the extension:
// "wxgod/references/god-persona". The served registry stays a flat key → body map.
function listPromptFiles(dir, prefix = '') {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...listPromptFiles(join(dir, e.name), rel));
    else if (e.isFile() && e.name.endsWith('.md')) out.push(rel);
  }
  return out;
}

const files = listPromptFiles(promptsDir);
const entries = files.map((f) => {
  const key = f.replace(/\.md$/, '');
  const b64 = Buffer.from(readFileSync(join(promptsDir, f), 'utf8'), 'utf8').toString('base64');
  return `  ${JSON.stringify(key)}: ${JSON.stringify(b64)},`;
});

const out = `// AUTO-GENERATED by scripts/build-prompts.mjs — do not edit by hand.
// Source: src/prompts/*.md. Run \`node scripts/build-prompts.mjs\` to regenerate.
/* eslint-disable */
const PROMPTS_B64: Record<string, string> = {
${entries.join('\n')}
};

/** Return the methodology body for a command, or null if not server-delivered. */
export function getCommandPrompt(command: string): string | null {
  const b64 = PROMPTS_B64[command];
  return b64 ? Buffer.from(b64, 'base64').toString('utf8') : null;
}

/** List the commands that have a server-delivered prompt. */
export function listPromptCommands(): string[] {
  return Object.keys(PROMPTS_B64);
}
`;

const dest = join(promptsDir, 'registry.ts');
writeFileSync(dest, out, 'utf8');
console.log(`build-prompts: wrote ${files.length} prompt(s) -> ${dest}`);
